
import { GoogleGenAI, Modality } from "@google/genai";
import type { ImageState } from '../types';

if (!process.env.API_KEY) {
    throw new Error("API_KEY environment variable is not set");
}

const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });

const fileToGenerativePart = (image: ImageState) => {
  return {
    inlineData: {
      data: image.base64,
      mimeType: image.mimeType,
    },
  };
};

export const generateVirtualTryOnImage = async (garmentImage: ImageState, modelImage: ImageState): Promise<string> => {
    const model = 'gemini-2.5-flash-image';
    const prompt = `Using the image of the person and the image of the garment, generate a new, photorealistic image. The person from the model photo should be wearing the garment from the clothing photo. Ensure the fit is natural and perfect. The final image should have a soft, neutral background with natural lighting.`;

    const garmentPart = fileToGenerativePart(garmentImage);
    const modelPart = fileToGenerativePart(modelImage);
    
    try {
        const response = await ai.models.generateContent({
            model: model,
            contents: {
                parts: [
                    { text: prompt },
                    garmentPart,
                    modelPart,
                ],
            },
            config: {
                responseModalities: [Modality.IMAGE, Modality.TEXT],
            },
        });

        // Find the image part in the response
        for (const part of response.candidates[0].content.parts) {
            if (part.inlineData && part.inlineData.mimeType.startsWith('image/')) {
                const base64ImageBytes: string = part.inlineData.data;
                return `data:${part.inlineData.mimeType};base64,${base64ImageBytes}`;
            }
        }

        throw new Error('No image was generated by the model. Please try a different prompt or images.');

    } catch (error) {
        console.error("Error calling Gemini API:", error);
        if (error instanceof Error && error.message.includes('API key not valid')) {
             throw new Error('The configured API key is invalid. Please check your configuration.');
        }
        throw new Error('Failed to generate image. The AI model may be overloaded or the images could not be processed.');
    }
};
